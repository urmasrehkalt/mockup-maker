// The parts of a user story sentence, in the project's content language.
const CONTENT = {
  et: {
    title: (p) => `${cap(p.role)} soovin ${p.action}, et ${p.benefit}.`,
    phrase: 'Rollina (lause algus)', phraseHint: 'nt Külastajana', action: 'soovin …', benefit: 'et …',
    want: 'soovin', soThat: ', et',
  },
  en: {
    title: (p) => `As ${p.role.replace(/^as\s+/i, '')}, I want to ${p.action.replace(/^to\s+/i, '')}, so that ${p.benefit}.`,
    phrase: 'As (role with article)', phraseHint: 'e.g. a visitor', action: 'I want to …', benefit: 'so that …',
    want: 'I want to', soThat: ', so that',
  },
};

const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const STORAGE_KEY = 'mockup-maker.lang';
let lang = readStored();

function readStored() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'et' || saved === 'en') return saved;
  } catch { /* storage may be unavailable */ }
  return 'et';
}

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = next === 'en' ? 'en' : 'et';
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* keep it for this page only */ }
  document.documentElement.lang = lang;
}

export function t(key, params = {}) {
  const text = STRINGS[lang][key] ?? STRINGS.et[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => params[name] ?? `{${name}}`);
}

/** A word of the story sentence ('phrase', 'action', ...) in a content language. */
export function contentText(language, key) {
  return (CONTENT[language] ?? CONTENT.et)[key];
}

/** The Connextra title for story parts, in the project's language. */
export function storyTitle(parts, language) {
  const benefit = (parts.benefit ?? '').trim().replace(/\.$/, '');
  return (CONTENT[language] ?? CONTENT.et).title({ role: parts.role_phrase.trim(), action: parts.action.trim(), benefit });
}

export function formatDateTime(iso) {
  return new Intl.DateTimeFormat(lang === 'en' ? 'en-GB' : 'et-EE', { dateStyle: 'medium', timeStyle: 'short' })
    .format(new Date(iso));
}

document.documentElement.lang = lang;
